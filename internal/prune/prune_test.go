func TestValidateProposalRequiresCompleteNonOverlappingActions(t *testing.T) {
	context := prune.Context{
		Schema:        prune.ContextSchema,
		ReviewID:      "review-one",
		ContextDigest: "sha256:" + strings.Repeat("1", 64),
		Inventory: inventory.Report{Files: []inventory.File{{
			Path: "README.md", Lines: 1, SHA256: "sha256:" + strings.Repeat("4", 64),
		}}},
		Artifacts: []prune.Artifact{
			{
				Kind:   prune.ArtifactRule,
				ID:     "keep-rule",
				Path:   ".software-standards/rules/keep-rule.md",
				SHA256: "sha256:" + strings.Repeat("2", 64),
				Origin: prune.OriginGenerated,
			},
			{
				Kind:   prune.ArtifactSkill,
				ID:     "orphan-skill",
				Path:   ".agents/skills/orphan-skill/SKILL.md",
				SHA256: "sha256:" + strings.Repeat("3", 64),
				Origin: prune.OriginUserAuthored,
			},
		},
		Capabilities: prune.CapabilityProfile{
			Capabilities: []prune.Capability{{
				ID:          "agent-skills-discovery",
				Status:      prune.CapabilitySupported,
				EvidenceIDs: []string{"host-run"},
			}},
		},
	}
	proposal := prune.Proposal{
		Schema:        prune.ProposalSchema,
		ReviewID:      "review-one",
		ContextDigest: context.ContextDigest,
		Actions: []prune.Action{{
			ID:          "keep-rule",
			Disposition: prune.DispositionKeep,
			Sources:     []prune.ArtifactRef{prune.Reference(context.Artifacts[0])},
			Rationale:   "Repository and host evidence still support this rule.",
			Confidence:  prune.ConfidenceHigh,
			RepositoryEvidence: []prune.EvidenceRef{{
				Path:   "README.md",
				Lines:  "1-1",
				SHA256: "sha256:" + strings.Repeat("4", 64),
			}},
			CapabilityRefs: []string{"agent-skills-discovery"},
			RequiredVerification: []prune.CheckRequirement{{
				ID: "review-check", Command: "ssb validate --repo .",
			}},
		}},
	}

	diagnostics := prune.ValidateProposal(context, proposal, t.TempDir())
	if len(diagnostics) != 1 ||
		!strings.Contains(diagnostics[0].Message, "orphan-skill") {
		t.Fatalf("diagnostics = %#v, want uncovered skill", diagnostics)
	}
}

func TestValidateProposalForcesUnknownProvenanceToUnableToDetermine(t *testing.T) {
	context := prune.Context{
		Schema:        prune.ContextSchema,
		ReviewID:      "review-one",
		ContextDigest: "sha256:" + strings.Repeat("1", 64),
		Inventory: inventory.Report{Files: []inventory.File{{
			Path: "README.md", Lines: 1, SHA256: "sha256:" + strings.Repeat("4", 64),
		}}},
		Artifacts: []prune.Artifact{{
			Kind:   prune.ArtifactRule,
			ID:     "unknown-rule",
			Path:   ".software-standards/rules/unknown-rule.md",
			SHA256: "sha256:" + strings.Repeat("2", 64),
			Origin: prune.OriginUnknown,
		}},
		Capabilities: prune.CapabilityProfile{
			Capabilities: []prune.Capability{{
				ID:          "agent-rules",
				Status:      prune.CapabilitySupported,
				EvidenceIDs: []string{"host-run"},
			}},
		},
	}
	action := prune.Action{
		ID:          "remove-unknown",
		Disposition: prune.DispositionRemove,
		Sources:     []prune.ArtifactRef{prune.Reference(context.Artifacts[0])},
		Rationale:   "The capability evidence suggests this is redundant.",
		Confidence:  prune.ConfidenceMedium,
		RepositoryEvidence: []prune.EvidenceRef{{
			Path:   "README.md",
			Lines:  "1-1",
			SHA256: "sha256:" + strings.Repeat("4", 64),
		}},
		CapabilityRefs: []string{"agent-rules"},
		RequiredVerification: []prune.CheckRequirement{{
			ID: "review-check", Command: "ssb validate --repo .",
		}},
	}
	proposal := prune.Proposal{
		Schema:        prune.ProposalSchema,
		ReviewID:      context.ReviewID,
		ContextDigest: context.ContextDigest,
		Actions:       []prune.Action{action},
	}

	diagnostics := prune.ValidateProposal(context, proposal, t.TempDir())
	if len(diagnostics) == 0 ||
		!strings.Contains(diagnostics[0].Message, "unable-to-determine") {
		t.Fatalf("diagnostics = %#v, want provenance block", diagnostics)
	}

	proposal.Actions[0].Disposition = prune.DispositionUnableToDetermine
	proposal.Actions[0].CapabilityRefs = nil
	proposal.Actions[0].RepositoryEvidence = nil
	proposal.Actions[0].UnresolvedQuestions = []string{"Who authored and adopted this rule?"}
	if diagnostics := prune.ValidateProposal(context, proposal, t.TempDir()); len(diagnostics) != 0 {
		t.Fatalf("unable-to-determine proposal rejected: %#v", diagnostics)
	}
}

func lifecycleRepository(t *testing.T) string {
	t.Helper()
	repo := t.TempDir()
	git(t, repo, "init", "-b", "main")
	writeFile(t, filepath.Join(repo, "README.md"), "fixture\n")
	git(t, repo, "add", "README.md")
	git(t, repo, "commit", "-m", "baseline")
	baseline := strings.TrimSpace(git(t, repo, "rev-parse", "HEAD"))
	writeFile(t, filepath.Join(repo, ".software-standards", "assessment.md"), "assessment\n")
	writeFile(t, filepath.Join(repo, ".software-standards", "rules", "keep-rule.md"), fmt.Sprintf(`---
schema: ssb.dev/rule/v2
id: keep-rule
title: Keep the rule
topic: maintainability
lenses:
  - kind: base
directive: prefer
scopes:
  - "**"
classification: guidance
importance: high
score:
  method: ssb-score-v1
  total: 70
  factors:
    prevalence: 15
    consistency: 15
    authority: 15
    risk: 15
    applicability: 10
confidence: high
baseline_commit: %s
evidence:
  - path: README.md
    lines: 1-1
    excerpt_sha256: %s
    authoritative: true
verification:
  proof_gap: No deterministic repository check covers this guidance.
---
Keep the rule.
`, baseline, fileDigest(t, filepath.Join(repo, "README.md"))))
	writeFile(t, filepath.Join(repo, ".agents", "skills", "orphan-skill", "SKILL.md"), `---
name: orphan-skill
description: A repository-authored skill that is not referenced by a rule.
metadata:
  topic: maintainability
---
Follow the workflow.
`)
	git(t, repo, "add", ".")
	git(t, repo, "commit", "-m", "adopt standards")
	return repo
}

func capabilityProfile(t *testing.T) string {
	t.Helper()
	dir := t.TempDir()
	evidencePath := filepath.Join(dir, "host-run.json")
	writeFile(t, evidencePath, `{"result":"supported"}`+"\n")
	profilePath := filepath.Join(dir, "capabilities.yaml")
	writeFile(t, profilePath, `schema: ssb.dev/capability-profile/v1
id: codex-example
host:
  name: codex
  version: 1.2.3
model:
  provider: openai
  id: gpt-example
observed_at: 2026-07-27T18:00:00Z
evidence:
  - id: host-run
    kind: conformance
    path: host-run.json
    sha256: `+fileDigest(t, evidencePath)+`
capabilities:
  - id: agent-skills-discovery
    status: supported
    evidence_ids:
      - host-run
`)
	return profilePath
}

func fileDigest(t *testing.T, path string) string {
	t.Helper()
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	sum := sha256.Sum256(data)
	return "sha256:" + hex.EncodeToString(sum[:])
}

func git(t *testing.T, dir string, args ...string) string {
	t.Helper()
	base := []string{"-c", "user.name=SSB Test", "-c", "user.email=ssb@example.invalid", "-C", dir}
	command := exec.Command("git", append(base, args...)...)
	output, err := command.CombinedOutput()
	if err != nil {
		t.Fatalf("git %s failed: %v\n%s", strings.Join(args, " "), err, output)
	}
	return string(output)
}

func writeFile(t *testing.T, path, contents string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(contents), 0o644); err != nil {
		t.Fatal(err)
	}
}
