func TestBuildContextInventoriesAllRulesAndRepositorySkills(t *testing.T) {
	repo := lifecycleRepository(t)
	profile := capabilityProfile(t)
	provenance := filepath.Join(t.TempDir(), "provenance.yaml")
	writeFile(t, provenance, `schema: ssb.dev/artifact-provenance/v1
artifacts:
  - path: .software-standards/rules/keep-rule.md
    sha256: `+fileDigest(t, filepath.Join(repo, ".software-standards", "rules", "keep-rule.md"))+`
    origin: generated
    declaration: Generated by the adopted SSB workflow.
  - path: .agents/skills/orphan-skill/SKILL.md
    sha256: `+fileDigest(t, filepath.Join(repo, ".agents", "skills", "orphan-skill", "SKILL.md"))+`
    origin: user-authored
    declaration: Authored and adopted directly by the repository maintainer.
`)

	ws, err := workspace.OpenForPrune(context.Background(), repo)
	if err != nil {
		t.Fatal(err)
	}
	got, err := prune.BuildContext(context.Background(), ws, prune.ContextOptions{
		ReviewID:        "review-one",
		Capabilities:    profile,
		Provenance:      provenance,
		InventoryLimits: inventory.DefaultLimits(),
	})
	if err != nil {
		t.Fatal(err)
	}
	if got.Schema != prune.ContextSchema || got.ReviewID != "review-one" ||
		got.BaselineCommit != ws.Baseline() || got.ContextDigest == "" {
		t.Fatalf("unexpected context identity: %#v", got)
	}
	if len(got.Artifacts) != 2 {
		t.Fatalf("artifacts = %#v, want rule and unreferenced skill", got.Artifacts)
	}
	if got.Artifacts[0].Kind != prune.ArtifactSkill ||
		got.Artifacts[0].ID != "orphan-skill" ||
		got.Artifacts[0].Origin != prune.OriginUserAuthored {
		t.Fatalf("unexpected skill artifact: %#v", got.Artifacts[0])
	}
	if got.Artifacts[1].Kind != prune.ArtifactRule ||
		got.Artifacts[1].ID != "keep-rule" ||
		got.Artifacts[1].Origin != prune.OriginGenerated {
		t.Fatalf("unexpected rule artifact: %#v", got.Artifacts[1])
	}
	if len(got.Capabilities.Capabilities) != 1 ||
		got.Capabilities.Capabilities[0].Status != prune.CapabilitySupported {
		t.Fatalf("unexpected capability profile: %#v", got.Capabilities)
	}
}

func TestBuildContextFailsClosedOnIncompleteInventory(t *testing.T) {
	repo := lifecycleRepository(t)
	ws, err := workspace.OpenForPrune(context.Background(), repo)
	if err != nil {
		t.Fatal(err)
	}
	_, err = prune.BuildContext(context.Background(), ws, prune.ContextOptions{
		ReviewID:     "review-one",
		Capabilities: capabilityProfile(t),
		InventoryLimits: inventory.Limits{
			MaxCandidateFiles: 1,
			MaxCandidateBytes: 1 << 20,
			MaxFileBytes:      1 << 20,
		},
	})
	if err == nil || !strings.Contains(err.Error(), "inventory coverage incomplete") {
		t.Fatalf("error = %v, want incomplete-coverage block", err)
	}
}

