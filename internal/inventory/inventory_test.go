func TestScanIncludesExactCandidateByteBoundaryAndStopsBeforeNextBlob(t *testing.T) {
	repo := newRepository(t)
	writeFile(t, filepath.Join(repo, "a.txt"), "aa")
	writeFile(t, filepath.Join(repo, "b.dat"), "b\x00b")
	git(t, repo, "add", ".")
	git(t, repo, "commit", "-m", "fixture")

	ws, err := workspace.OpenForInspect(context.Background(), repo)
	if err != nil {
		t.Fatal(err)
	}
	report, err := inventory.Scan(context.Background(), ws, inventory.Limits{
		MaxCandidateFiles: 10,
		MaxCandidateBytes: 2,
		MaxFileBytes:      1 << 10,
	})
	if err != nil {
		t.Fatal(err)
	}

	if !report.Truncated ||
		!strings.Contains(report.TruncationReason, "max_candidate_bytes=2") {
		t.Fatalf("byte truncation not disclosed: %#v", report)
	}
	if report.CandidateFiles != 2 || report.CandidateBytes != 5 ||
		report.ScannedFiles != 1 || report.ScannedBytes != 2 ||
		report.RemainingCandidateFiles != 1 || report.RemainingCandidateBytes != 3 {
		t.Fatalf("candidate accounting is inconsistent: %#v", report)
	}
	if len(report.Files) != 1 || report.Files[0].Path != "a.txt" {
		t.Fatalf("exact-boundary file was not indexed: %#v", report.Files)
	}
	if report.IndexedFiles != len(report.Files) {
		t.Fatalf("indexed_files = %d, want %d", report.IndexedFiles, len(report.Files))
	}
	if report.Excluded.Binary != 0 {
		t.Fatalf("over-budget binary blob was read: %#v", report.Excluded)
	}
}

