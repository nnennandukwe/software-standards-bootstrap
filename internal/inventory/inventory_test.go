func TestScanBudgetsEveryCandidateBeforeContentExclusion(t *testing.T) {
	repo := newRepository(t)
	writeFile(t, filepath.Join(repo, "a-binary.dat"), "a\x00b")
	writeFile(t, filepath.Join(repo, "b-generated.go"), "// Code generated by fixture. DO NOT EDIT.\n")
	writeFile(t, filepath.Join(repo, "c-safe.txt"), "safe\n")
	git(t, repo, "add", ".")
	git(t, repo, "commit", "-m", "fixture")

	ws, err := workspace.OpenForInspect(context.Background(), repo)
	if err != nil {
		t.Fatal(err)
	}
	report, err := inventory.Scan(context.Background(), ws, inventory.Limits{
		MaxCandidateFiles: 2,
		MaxCandidateBytes: 1 << 20,
		MaxFileBytes:      1 << 10,
	})
	if err != nil {
		t.Fatal(err)
	}

	if !report.Truncated {
		t.Fatalf("candidate file budget did not truncate report: %#v", report)
	}
	if len(report.Files) != 0 {
		t.Fatalf("over-budget safe file was read: %#v", report.Files)
	}
	if report.Excluded.Binary != 1 || report.Excluded.Generated != 1 {
		t.Fatalf("scanned content exclusions = %#v, want one binary and one generated", report.Excluded)
	}

	encoded, err := json.Marshal(report)
	if err != nil {
		t.Fatal(err)
	}
	var fields map[string]any
	if err := json.Unmarshal(encoded, &fields); err != nil {
		t.Fatal(err)
	}
	for key, want := range map[string]float64{
		"candidate_files":           3,
		"scanned_files":             2,
		"indexed_files":             0,
		"remaining_candidate_files": 1,
	} {
		if got := fields[key]; got != want {
			t.Errorf("%s = %#v, want %.0f", key, got, want)
		}
	}
}

